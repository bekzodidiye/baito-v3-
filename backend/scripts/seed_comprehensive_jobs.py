        # Also reopen previously cancelled good demo jobs if any
        prev_jobs = db.query(models.Job).filter(models.Job.status == JobStatus.CANCELLED).all()
        reopened = 0
        for pj in prev_jobs:
            is_junk = any(s in pj.title.lower() for s in ['arxiv', 'fesf', 'fekh', 'tttt', 'dwdw', 'verr', 'dawf', 'test'])
